// Helper to generate products for a category
const generateProducts = (
  category: CategoryKey,
  startId: number,
  items: { name: string; basePrice: number; hasDiscount?: boolean }[]
): Product[] => {
  return items.map((item, index) => {
    const id = startId + index;
    const originalPrice = item.hasDiscount ? Math.round(item.basePrice * 1.3) : undefined;
    // Use real image if available, otherwise use placeholder
    const productImage = productImages[item.name] || placeholderImg;
    return {
      id,
      title: item.name,
      price: item.basePrice,
      originalPrice,
      sku: `${category.toUpperCase().slice(0, 3)}-${String(id).padStart(4, '0')}`,
      img: productImage,
      category,
      badge: item.hasDiscount ? 'SALE' : undefined,
    };
  });
};

