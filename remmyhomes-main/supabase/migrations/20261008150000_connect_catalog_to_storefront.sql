ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS storefront_id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100000);

CREATE UNIQUE INDEX IF NOT EXISTS products_storefront_id_key
  ON public.products (storefront_id);

CREATE OR REPLACE VIEW public.product_visibility AS
  SELECT storefront_id, is_active
  FROM public.products;

GRANT SELECT ON public.product_visibility TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.decrement_product_stock(_product_id integer, _qty integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  updated_rows integer;
BEGIN
  IF _qty IS NULL OR _qty <= 0 THEN
    RETURN false;
  END IF;

  UPDATE public.products
     SET stock = stock - _qty,
         updated_at = now()
   WHERE storefront_id = _product_id
     AND is_active = true
     AND stock >= _qty;
  GET DIAGNOSTICS updated_rows = ROW_COUNT;
  RETURN updated_rows > 0;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.decrement_product_stock(integer, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.decrement_product_stock(integer, integer) TO service_role;

CREATE OR REPLACE FUNCTION public.restore_product_stock(_product_id integer, _qty integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF _qty IS NULL OR _qty <= 0 THEN
    RETURN;
  END IF;

  UPDATE public.products
     SET stock = stock + _qty,
         updated_at = now()
   WHERE storefront_id = _product_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.restore_product_stock(integer, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.restore_product_stock(integer, integer) TO service_role;
